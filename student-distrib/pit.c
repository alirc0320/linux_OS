#define Channel_data_port  0x40
#define PIT_MODE           0x43
#define PIT_IRQ            0
#define SET_ACCESS_MODE    0x36       // 00110110

/*
 * Initialize Programmable Interval Timer (PIT)
 *
 * Inputs: None
 * Outputs: None
 * Function: Configures the PIT with a divisor for desired frequency, enabling IRQ0.
 */
void init_pit(){

    unsigned int divisor = 1193180 / 100;   // 1193180 is the PIT frequency. Reload = PIT/Desired
    // Send the divisor (LSB followed by MSB)
    outb(SET_ACCESS_MODE, PIT_MODE);
    outb(divisor & 0xFF, Channel_data_port);             // LSB
    outb((divisor >> 8) & 0xFF, Channel_data_port);      // MSB
    enable_irq(PIT_IRQ);
   return;

}

/*
 * PIT interrupt handler
 *
 * Inputs: None
 * Outputs: None
 * Function: Handles the interrupt generated by the Programmable Interval Timer (PIT)
 *           and gives the CPU to the next terminal's process (round robin).
 */
void pit_interrupt(){
    send_eoi(PIT_IRQ); // EOI first, the context switch may not come back here for a while
    scheduler();
}

/*
 * Round robin scheduler
 *
 * Inputs: None
 * Outputs: None
 * Function: Saves the running terminal's kernel stack, swaps in the next terminal's
 *           process state (pcb array, active pid, paging, TSS, vidmap) and switches
 *           to its kernel stack. A terminal that has not started yet begins on its
 *           bootstrap stack, which executes its base shell.
 */
void scheduler(void){
    uint32_t cur = sched_terminal;
    uint32_t next = (cur + 1) % NUM_TERMINALS;
    uint32_t slot;
    int i;

    //swapping out pcb array - between global and terminal pcb array
    for (i = 0; i < MAX_PROCESSES; i++) {
        terminal_array[cur].pcb_array[i] = pcb_array[i];
        pcb_array[i] = terminal_array[next].pcb_array[i];
    }
    terminal_array[cur].pid = target_pid;
    target_pid = terminal_array[next].pid;
    sched_terminal = next;

    if (terminal_array[next].turned_on) {
        //map in the program image and kernel stack of the process we are resuming
        slot = pcb_array[target_pid]->global_pcb_value;
        program_pages(slot);
        tss.ss0 = KERNEL_DS;
        tss.esp0 = KERNEL_STACK_TOP(slot);
    } else {
        terminal_array[next].turned_on = 1; //its bootstrap stack will execute shell
    }

    update_vidmap();
    context_switch(&terminal_array[cur].esp, terminal_array[next].esp);
}
